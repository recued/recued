#!/usr/bin/env node
/**
 * D-172 step 5b — bundle the reception drop-link resumable uploader.
 *
 * Bundles `packages/ui-shared/src/upload/reception-drop-uploader.ts` (the shared
 * engine + HTTP transport + reception callers + the form bootstrap) into ONE
 * self-contained, minified IIFE and emits it as a committed string constant
 * (`RECEPTION_DROP_UPLOADER_JS`) in
 * `backend/server/src/ports/reception/drop-uploader-bundle.generated.ts`.
 *
 * Why an IIFE string (not a build/ file like the webclient PWA):
 *   the server serves this script as a SUBSTRATE-BUNDLED static asset (the same
 *   inline-constant model as `static-assets.ts`' style.css), under the drop
 *   page's strict per-render nonce'd CSP. Shipping it as a committed constant
 *   keeps the server's "no runtime FS read" property AND lets `static-assets.ts`
 *   compute the SRI (`sha384`) over the exact bytes it serves — so the
 *   integrity attribute can never drift from the served file (step 5c).
 *
 * IIFE (not ESM) because the drop page loads it as a CLASSIC
 * `<script nonce integrity src>` (not `type=module`), and it self-mounts on load.
 *
 * Run when the uploader source changes:
 *   npm run -w @recued/server build:reception-uploader
 * (an invariants guard test — `d-172-reception-uploader-bundle.test.ts` — locks
 * the properties that matter: the served bytes match the constant, the SRI is
 * consistent, and the bundle stays WS-free. It does NOT byte-compare a fresh
 * build, which would be flaky under the `^esbuild` range.)
 */

import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const SERVER_ROOT = resolve(__dirname, '..');
const REPO_ROOT = resolve(SERVER_ROOT, '..', '..');
const UI_SHARED = join(REPO_ROOT, 'packages', 'ui-shared');
const ENTRY = join(UI_SHARED, 'src', 'upload', 'reception-drop-uploader.ts');
const OUT = join(
  SERVER_ROOT,
  'src',
  'ports',
  'reception',
  'drop-uploader-bundle.generated.ts',
);

console.log('[build-reception-uploader] bundling', ENTRY);
const result = await build({
  entryPoints: [ENTRY],
  bundle: true,
  // Classic script (self-mounts on load) under the drop page's nonce'd CSP.
  format: 'iife',
  platform: 'browser',
  target: ['es2022', 'chrome120', 'firefox120', 'safari17'],
  // Resolve TS source over any prebuilt dist/ (same pattern as the app builds);
  // the type-only `@recued/contracts` import is erased, so nothing pulls the
  // contracts barrel (or the WS framing) into this visitor-facing bundle.
  resolveExtensions: ['.ts', '.tsx', '.mjs', '.js', '.json'],
  tsconfig: join(UI_SHARED, 'tsconfig.json'),
  minify: true,
  write: false,
  legalComments: 'none',
  logLevel: 'info',
});

const out = result.outputFiles[0];
if (!out) throw new Error('esbuild produced no output');
const code = out.text;
const sha384 = createHash('sha384').update(out.contents).digest('base64');

const banner =
  '/* GENERATED by backend/server/scripts/build-reception-uploader.mjs — do not\n' +
  ' * edit by hand. Edit the uploader source under\n' +
  ' * `packages/ui-shared/src/upload/` then run\n' +
  ' * `npm run -w @recued/server build:reception-uploader`. */\n\n';

const body =
  '/** The reception drop-link resumable uploader, bundled as ONE self-contained\n' +
  ' *  minified IIFE. Served as the `drop-uploader.js` reception static asset under\n' +
  ' *  a per-render nonce + SRI (D-172 step 5b/5c). The SRI is recomputed over these\n' +
  " *  bytes at module load in `static-assets.ts`, so it can't drift. */\n" +
  `export const RECEPTION_DROP_UPLOADER_JS = ${JSON.stringify(code)};\n\n` +
  '/** The bundle’s `sha384` (base64) at build time — informational; the served\n' +
  ' *  integrity is recomputed from the bytes above (static-assets.ts), so this is\n' +
  ' *  not load-bearing. The invariants guard test cross-checks it against that\n' +
  ' *  recomputed SRI. */\n' +
  `export const RECEPTION_DROP_UPLOADER_SHA384_AT_BUILD = ${JSON.stringify(sha384)};\n`;

writeFileSync(OUT, banner + body, 'utf8');
console.log(
  `[build-reception-uploader] wrote ${OUT} (${code.length} bytes JS, sha384-${sha384})`,
);
