#!/usr/bin/env node
/**
 * Generate the four closed D-259 reconciliation targets as TypeScript data.
 *
 * `community/` is repository-only: npm packages and Docker runtime images ship
 * `dist/`, not the pack corpus. The boot reconciler must therefore carry its
 * reviewed offline recovery artifacts in the server bundle. The runtime still
 * prefers an exact root pack file when one exists (source/development layout),
 * and independently checks the canonical target hash either way.
 *
 * Regenerate whenever one of the four target manifests changes:
 *   npm run gen:pack-reconciliation
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const PACK_RECONCILIATION_TARGET_SLUGS = Object.freeze([
  'codex-pack',
  'yt-dlp',
  'cloudflared',
  'ollama',
]);

/** Read only the closed root-level target set. A missing/misnamed artifact is a
 * generation error, never a silently smaller embed. */
export const derivePackReconciliationTargets = (repoRoot) => {
  const packDir = join(repoRoot, 'community', 'packs');
  const targets = {};
  for (const slug of PACK_RECONCILIATION_TARGET_SLUGS) {
    const manifest = JSON.parse(readFileSync(join(packDir, `${slug}.json`), 'utf8'));
    if (manifest?.slug !== slug) {
      throw new Error(`reconciliation target ${JSON.stringify(slug)} has mismatched slug`);
    }
    targets[slug] = manifest;
  }
  return targets;
};

export const renderPackReconciliationModule = (targets) =>
  `/* GENERATED by backend/server/scripts/gen-bundled-pack-reconciliation.mjs — DO NOT EDIT.
 *
 * Embeds the closed D-259 recovery targets because deployed npm/Docker servers
 * do not ship community/. Regenerate: npm run gen:pack-reconciliation. */
/* eslint-disable */
// prettier-ignore
import type { BulkPackManifest } from '@recued/contracts';

// prettier-ignore
export const BUNDLED_PACK_RECONCILIATION_TARGETS: Readonly<Record<string, BulkPackManifest>> =
  ${JSON.stringify(targets, null, 2)} as unknown as Readonly<Record<string, BulkPackManifest>>;
`;

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
  const out = join(
    repoRoot,
    'backend',
    'server',
    'src',
    'bundled-pack-reconciliation.generated.ts',
  );
  const targets = derivePackReconciliationTargets(repoRoot);
  writeFileSync(out, renderPackReconciliationModule(targets));
  console.log(
    `[gen-bundled-pack-reconciliation] wrote ${out}\n  packs: ${Object.keys(targets).join(', ')}`,
  );
}
