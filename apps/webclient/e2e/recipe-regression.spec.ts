import { expect,test,type Page } from '@playwright/test';
const open = async (page: Page,scenario = '1') => {
  await page.goto(`/kitchen-harness.html?surface=recipe&fixture=regression&regression=${scenario}`);
  const panel = page.locator('[data-recipe-regression]'); await panel.locator('summary').first().click();
  await expect(panel.locator('[data-regression-status]')).toContainText('No saved tests yet.'); return panel;
};
const saveCase = async (page: Page) => {
  const panel = page.locator('[data-recipe-regression]');
  await panel.getByRole('textbox',{ name: 'Case name',exact: true }).fill('Empty input');
  await panel.getByRole('button',{ name: 'Add check',exact: true }).click();
  await panel.getByRole('textbox',{ name: 'Expected value (JSON)',exact: true }).fill('0');
  await panel.getByRole('button',{ name: 'Save test version',exact: true }).click();
  await expect(panel.locator('[data-regression-status]')).toContainText('Saved test version 1.'); return panel;
};
const workingInput = (page: Page) => page.locator('[data-recued-recipe-editor-step="count"] [data-recued-recipe-editor-field="param:input"]');
for (const width of [280,1280]) {
  test(`saved assertions survive reload and expose changed step inputs and outputs at ${width}px`,async ({ page }) => {
    await page.setViewportSize({ width,height: 900 }); await open(page); const panel = await saveCase(page);
    await panel.getByRole('button',{ name: 'Run test suite',exact: true }).click();
    await expect(panel.locator('[data-regression-results]')).toContainText('Working recipe: 1 passed, 0 failed. 0 cases changed.');
    await workingInput(page).fill('[1,2]'); await workingInput(page).press('Tab');
    await expect(panel.locator('[data-regression-status]')).toHaveAttribute('data-state','stale');
    await panel.getByRole('button',{ name: 'Run test suite',exact: true }).click();
    await expect(panel.locator('[data-regression-results]')).toContainText('Working recipe: 0 passed, 1 failed. 1 cases changed.');
    await panel.locator('[data-regression-results] summary').click();
    await expect(panel.locator('[data-regression-results]')).toContainText('changed: input, output');
    await expect(panel.locator('[data-regression-results]')).toContainText('Before'); await expect(panel.locator('[data-regression-results]')).toContainText('After');
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.reload(); await panel.locator('summary').first().click();
    await expect(panel.locator('[data-regression-status]')).toContainText('Loaded test version 1.');
    await expect(panel.getByRole('textbox',{ name: 'Case name',exact: true })).toHaveValue('Empty input');
    await panel.getByRole('button',{ name: 'Run test suite',exact: true }).click();
    await expect(panel.locator('[data-regression-results]')).toContainText('Working recipe: 1 passed, 0 failed.');
  });
  test(`historical suites keep their own baseline and assertions at ${width}px`,async ({ page }) => {
    await page.setViewportSize({ width,height: 900 }); await open(page); const panel = await saveCase(page);
    await workingInput(page).fill('[1,2]'); await workingInput(page).press('Tab');
    await panel.getByRole('button',{ name: 'Use working recipe as baseline',exact: true }).click();
    await panel.getByRole('textbox',{ name: 'Expected value (JSON)',exact: true }).fill('2');
    await panel.getByRole('button',{ name: 'Save test version',exact: true }).click();
    await expect(panel.locator('[data-regression-status]')).toContainText('Saved test version 2.');
    await panel.getByRole('combobox',{ name: 'Saved test version',exact: true }).selectOption('1');
    await expect(panel.locator('[data-regression-status]')).toContainText('Loaded test version 1.');
    await expect(panel.getByRole('textbox',{ name: 'Expected value (JSON)',exact: true })).toHaveValue('0');
    await panel.getByRole('button',{ name: 'Run test suite',exact: true }).click();
    await expect(panel.locator('[data-regression-results]')).toContainText('0 passed, 1 failed');
    await panel.getByRole('combobox',{ name: 'Saved test version',exact: true }).selectOption('2');
    await panel.getByRole('button',{ name: 'Run test suite',exact: true }).click();
    await expect(panel.locator('[data-regression-results]')).toContainText('1 passed, 0 failed. 0 cases changed.');
  });
  test(`save retry reuses its request and unfinished JSON never reports a passing suite at ${width}px`,async ({ page }) => {
    await page.setViewportSize({ width,height: 900 }); const panel = await open(page,'lost');
    await panel.getByRole('textbox',{ name: 'Case name',exact: true }).fill('Keep my case');
    await panel.getByRole('button',{ name: 'Save test version',exact: true }).click();
    await expect(panel.getByRole('alert')).toContainText('Save reply lost.');
    await expect(panel.getByRole('textbox',{ name: 'Case name',exact: true })).toHaveValue('Keep my case');
    await panel.getByRole('button',{ name: 'Retry saving version',exact: true }).click();
    await expect(panel.locator('[data-regression-status]')).toContainText('Saved test version 1.');
    expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem('recued-regression-browser')!).head)).toBe(1);
    await panel.getByRole('button',{ name: 'Run test suite',exact: true }).click();
    await expect(panel.locator('[data-regression-results]')).toContainText('1 passed');
    await panel.getByRole('textbox',{ name: 'Sample data (JSON)',exact: true }).fill('{');
    await expect(panel.getByRole('button',{ name: 'Run test suite',exact: true })).toBeDisabled();
    await panel.getByRole('button',{ name: 'Save test version',exact: true }).click();
    await expect(panel.getByRole('alert')).toBeVisible();
    await expect(panel.getByRole('textbox',{ name: 'Sample data (JSON)',exact: true })).toHaveValue('{');
    await expect(panel.locator('[data-regression-results]')).toHaveCount(0);
  });
  test(`cancellation clears the result and working edits during a run mark it stale at ${width}px`,async ({ page }) => {
    await page.setViewportSize({ width,height: 900 }); await open(page,'slow'); let panel = await saveCase(page);
    await panel.getByRole('button',{ name: 'Run test suite',exact: true }).click();
    await panel.getByRole('button',{ name: 'Cancel suite',exact: true }).click();
    await expect(panel.getByRole('alert')).toContainText('Test suite cancelled.'); await expect(panel.locator('[data-regression-results]')).toHaveCount(0);
    await page.goto('/kitchen-harness.html?surface=recipe&fixture=regression&regression=defer');
    panel = page.locator('[data-recipe-regression]'); await panel.locator('summary').first().click();
    await expect(panel.locator('[data-regression-status]')).toContainText('Loaded test version 1.');
    await panel.getByRole('button',{ name: 'Run test suite',exact: true }).click();
    await workingInput(page).fill('[1]'); await workingInput(page).press('Tab');
    await expect(panel.locator('[data-regression-status]')).toHaveAttribute('data-state','stale');
    await expect(panel.locator('[data-regression-status]')).toContainText('Recipe changed since this suite started.');
  });
  test(`check editing retains keyboard focus and test-save shortcuts do not save the recipe at ${width}px`,async ({ page }) => {
    await page.setViewportSize({ width,height: 900 }); const panel = await open(page);
    await panel.getByRole('button',{ name: 'Duplicate case',exact: true }).press('Enter');
    await expect(panel.getByRole('textbox',{ name: 'Case name',exact: true })).toBeFocused();
    await panel.getByRole('button',{ name: 'Remove case',exact: true }).press('Enter');
    await expect(panel.getByRole('textbox',{ name: 'Case name',exact: true })).toBeFocused();
    await panel.getByRole('button',{ name: 'Add check',exact: true }).focus();
    await panel.getByRole('button',{ name: 'Add check',exact: true }).press('Enter');
    await expect(panel.getByRole('combobox',{ name: 'Check type',exact: true })).toBeFocused();
    await panel.getByRole('button',{ name: 'Add check',exact: true }).press('Enter');
    await expect(panel.getByRole('combobox',{ name: 'Check type',exact: true }).last()).toBeFocused();
    await panel.getByRole('button',{ name: 'Remove check',exact: true }).last().press('Enter');
    await expect(panel.getByRole('combobox',{ name: 'Check type',exact: true })).toBeFocused();
    await panel.getByRole('button',{ name: 'Remove check',exact: true }).press('Enter');
    await expect(panel.getByRole('button',{ name: 'Add check',exact: true })).toBeFocused();
    await panel.getByRole('button',{ name: 'Add check',exact: true }).press('Enter');
    const kind = panel.getByRole('combobox',{ name: 'Check type',exact: true }); await kind.focus(); await kind.selectOption('step_status');
    await expect(kind).toBeFocused();
    await panel.getByRole('textbox',{ name: 'Case name',exact: true }).fill('Keyboard case');
    await panel.getByRole('textbox',{ name: 'Case name',exact: true }).press('ControlOrMeta+s');
    await expect(panel.locator('[data-regression-status]')).toContainText('Saved test version 1.');
    expect(await page.evaluate(() => window.__harness.recipeSaveBodies.length)).toBe(0);
    await panel.getByRole('button',{ name: 'Run test suite',exact: true }).click();
    await expect(panel.locator('[data-regression-results]')).toContainText('1 passed, 0 failed');
    page.once('dialog',dialog => dialog.accept()); await panel.getByRole('button',{ name: 'Delete saved tests',exact: true }).click();
    await expect(panel.locator('[data-regression-status]')).toContainText('Saved tests deleted.');
    expect(await page.evaluate(() => window.__harness.recipeSaveBodies.length)).toBe(0);
  });
  test(`a late save reply cannot authorize overwriting a newer tab at ${width}px`,async ({ page }) => {
    await page.setViewportSize({ width,height: 900 }); const panel = await open(page,'superseded');
    await panel.getByRole('textbox',{ name: 'Case name',exact: true }).fill('My case');
    await panel.getByRole('button',{ name: 'Save test version',exact: true }).click();
    await expect(panel.locator('[data-regression-status]')).toContainText('Newer tests exist');
    await panel.getByRole('textbox',{ name: 'Case name',exact: true }).fill('Keep my edits');
    await panel.getByRole('button',{ name: 'Save test version',exact: true }).click();
    await expect(panel.getByRole('alert')).toContainText('Tests changed in another tab');
    await expect(panel.getByRole('textbox',{ name: 'Case name',exact: true })).toHaveValue('Keep my edits');
    page.once('dialog',dialog => dialog.accept()); await panel.getByRole('button',{ name: 'Load saved tests',exact: true }).click();
    await expect(panel.getByRole('textbox',{ name: 'Case name',exact: true })).toHaveValue('Other tab case');
    expect(await page.evaluate(() => JSON.parse(sessionStorage.getItem('recued-regression-browser')!).head)).toBe(2);
  });
}
