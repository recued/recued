/** Render the `ask` landing page. Pure — given the same input it emits
 *  the same HTML. Dispatches on `ask.status`: `open` → the option form
 *  (uses `form_nonce` + `action`); `answered` / `handled` → the honest
 *  "already answered" page. */
export const renderAskLandingHtml = (
  input: AskLandingRenderInput,
): string => {
  const { ask } = input;
  if (ask.status === 'open') {
    return renderShell({
      title: ask.message.title ?? DEFAULT_OPEN_HEADING,
      heading: ask.message.title ?? DEFAULT_OPEN_HEADING,
      phrase: input.verification_phrase,
      inner: renderOpenBody(input),
    });
  }
  return renderShell({
    title: ANSWERED_HEADING,
    heading: ANSWERED_HEADING,
    phrase: input.verification_phrase,
    inner: renderAnsweredBody(ask),
  });
};

/** Decode an `application/x-www-form-urlencoded` landing-page POST body
 *  into an `AskLandingSubmission`, or an `{ error }` when it is not a
 *  usable submission. Pure + self-contained — every field the server
 *  route needs (`ask_id`, the chosen `option`, the `form_nonce`) rides
 *  in the body as a hidden / radio field, so the decoder never needs the
 *  request URL.
 *
 *  `unknown_field` — the body carried a key outside the closed list (a
 *  tampered or malformed submission). `malformed` — a required field is
 *  missing or empty. The chosen `option` is NOT validated against any
 *  ask here: `block.submitAnswer` re-validates it (and dedups) against
 *  the persisted `PendingAsk`. */
export const parseAskLandingSubmission = (
  rawBody: string,
): AskLandingSubmission | { error: 'unknown_field' | 'malformed' } => {
  const params = new URLSearchParams(rawBody);
  const edits: Record<string, string> = {};
  let sawEdit = false;
  for (const [key, value] of params) {
    if (ALLOWED_SUBMISSION_KEYS.has(key)) continue;
    if (!key.startsWith(EDIT_KEY_PREFIX)) return { error: 'unknown_field' };
    const argKey = key.slice(EDIT_KEY_PREFIX.length);
    // A bare `edit.` names nothing, and `__proto__` / `constructor` /
    // `prototype` are refused here as well as at the allowlist — the
    // decoder builds a plain object and must not be the layer that hands
    // one a poisoned key. (`validateEditsAgainstSchema` refuses them too;
    // this is the defense-in-depth half.)
    if (argKey.length === 0 || FORBIDDEN_EDIT_KEYS.has(argKey)) {
      return { error: 'unknown_field' };
    }
    // A repeated key is a tampered / malformed body, not a last-wins
    // convenience: silently keeping one of two conflicting values for the
    // SAME arg is exactly the kind of quiet choice an approval must not make.
    if (Object.hasOwn(edits, argKey)) return { error: 'unknown_field' };
    edits[argKey] = value;
    sawEdit = true;
  }
  const ask_id = (params.get('ask_id') ?? '').trim();
  const option = (params.get('option') ?? '').trim();
  const form_nonce = (params.get('form_nonce') ?? '').trim();
  if (
    ask_id.length === 0 ||
    option.length === 0 ||
    form_nonce.length === 0
  ) {
    return { error: 'malformed' };
  }
  return {
    reply: { ask_id, option, via: LANDING_REPLY_VIA },
    form_nonce,
    ...(sawEdit ? { edits } : {}),
  };
};
