/** The channel a landing-page answer is attributed to. The landing page
 *  is the email channel's HTTP answer surface (N.4 — a public-reachable
 *  server's additional email-channel path), so a reply through it counts
 *  as a reply `via` the `email` channel.
 *
 *  ⚠ D-210 audit finding 15 — THAT PREMISE IS NO LONGER TRUE, and the constant
 *  did not follow it. The answer link is now attached to EVERY inline channel
 *  (`index.ts`: `if (deps.askAnswerLink === undefined || channel.capability !==
 *  'inline') return message`), so an approval tapped from a Slack card is
 *  durably recorded as an email reply — on the ask row and in the answer-audit
 *  activity row (`… via ${record.answered_via}`). The attribution is simply
 *  wrong for every non-email inline channel.
 *
 *  ⛔ NOT fixed by swapping the constant. The page cannot know which channel the
 *  reader came from — the URL is identical on all of them — so a truthful value
 *  has to be carried IN the link, which is exactly the per-link attribution
 *  Appendix B already names as an open carry. And a new `ask_landing` channel
 *  name is not a drop-in either: `ChannelName` is a closed set that also drives
 *  readiness probes, the user-togglable `RemoteChannelName` subset, and the
 *  fan-out matrix.
 *
 *  ⏭ The fix is: stamp the originating channel into the answer link at fan-out,
 *  parse it back at the port, and attribute the reply to it — defaulting to
 *  `email` only when absent (an old link). Left NAMED rather than half-done,
 *  because a wrong attribution that looks deliberate is worse than one that is
 *  documented as wrong. ⇒ [[a_reversed_rulings_reasoning_outlives_its_location]] */
const LANDING_REPLY_VIA: ChannelName = 'email';

/** The closed list of form keys the POST decoder accepts — any other key
 *  rejects the submission (`unknown_field`). Defense-in-depth, mirroring
 *  the D-149 reception handlers' `ALLOWED_FORM_KEYS`. */
const ALLOWED_SUBMISSION_KEYS: ReadonlySet<string> = new Set([
  'form_nonce',
  'ask_id',
  'option',
]);

/** D-210 A.8 3d-2c — the namespace every arg-edit field submits under.
 *
 *  The allowlist above stays CLOSED. Edits are admitted by PREFIX instead
 *  of by widening it, so a tampered body still cannot introduce a bare
 *  top-level key, and the decoder never has to know what a valid arg name
 *  is — it hands the server raw `key → string` pairs and the server checks
 *  them against the operation's `ArgEditSchema` allowlist
 *  (`validateEditsAgainstSchema`, which refuses any non-allowlisted key
 *  BEFORE any write). Two layers, each with the knowledge it actually has:
 *  shape here, authority there. */
const EDIT_KEY_PREFIX = 'edit.';

/** Prototype-pollution keys, refused at the decoder as well as at the
 *  server's allowlist. */
const FORBIDDEN_EDIT_KEYS: ReadonlySet<string> = new Set([
  '__proto__',
  'constructor',
  'prototype',
]);

const DEFAULT_OPEN_HEADING = 'Your input is needed';
const ANSWERED_HEADING = 'Already answered';

/** The HTTP response headers the server route serving this page MUST
 *  set on every GET / POST response.
 *
 *  `frame-ancestors` is one of the few CSP directives a browser honours
 *  ONLY from a real response header — it is silently ignored inside a
 *  `<meta http-equiv>` CSP. The page records a user decision on POST, so
 *  clickjacking protection cannot be left to the meta tag; it rides here
 *  as `x-frame-options: DENY` (what D-149's reception `writeHtmlResponse`
 *  also emits). The rest mirror that same reception header set — no
 *  referrer leak, no MIME sniffing, never cached. The meta-tag CSP in
 *  the rendered `<head>` still carries the directives that DO work from
 *  `<meta>` (`default-src` / `style-src` / `form-action` / `base-uri`).
 *
 *  The leaf renders HTML and cannot set headers — the server-wiring
 *  slice spreads this constant onto its response. */
export const ASK_LANDING_RESPONSE_HEADERS: Readonly<Record<string, string>> = {
  'x-frame-options': 'DENY',
  'referrer-policy': 'no-referrer',
  'x-content-type-options': 'nosniff',
  'cache-control': 'no-store',
};

// ── Render input ───────────────────────────────────────────────────

/** One label→value row of the "what will happen" block (D-210 A.8 3d-2b).
 *
 *  PRE-FORMATTED BY THE SERVER, deliberately. The leaf is a renderer: it
 *  escapes and lays out. Deciding what a `datetime` arg reads as (and in
 *  which named zone), what an absent value reads as, and where a long
 *  value is cut are all claims about the held operation — they belong with
 *  the side that can resolve the operation, not in a notification channel.
 *  `value` is therefore display text, already final. */
export interface AskLandingDetail {
  label: string;
  value: string;
  /** D-210 A.8 3d-2c — present ⇒ render an editable control instead of
   *  static text, and the submitted value rides `edit.<key>`.
   *
   *  Fully resolved by the server: which control, what the value attribute
   *  reads, and (for a `datetime-local`) WHICH ZONE that wall clock is in.
   *  The leaf never derives any of it — a control is a promise about what
   *  the submitted value will mean, and only the side that can also PARSE
   *  it back can make that promise. Absent ⇒ the 3d-2b read-only row. */
  edit?: AskLandingEditControl;
}

/** The rendered form control for one editable arg. */
export interface AskLandingEditControl {
  /** Arg key, WITHOUT the `edit.` submission prefix. */
  key: string;
  control: 'text' | 'textarea' | 'number' | 'datetime-local' | 'checkbox';
  /** The `value` attribute. Ignored for `checkbox` (which uses `checked`). */
  value: string;
  checked?: boolean;
  required?: boolean;
  min?: number;
  max?: number;
  pattern?: string;
}

/** What `renderAskLandingHtml` is handed. The `ask` is the block's own
 *  durable `PendingAsk`; `form_nonce` + `action` are server-routing
 *  knowledge the server HTTP route supplies. */
export interface AskLandingRenderInput {
  /** The pending ask to render. `status: 'open'` → the option form;
   *  `answered` / `handled` → the honest "already answered" page. */
  ask: PendingAsk;
  /** The held operation's concrete details — what this approval actually
   *  commits to, rendered above the options so the decision is made with
   *  the values in view rather than from the prose alone.
   *
   *  Absent / empty ⇒ no block (the pre-3d-2b page, byte-identical). That
   *  is the honest state for every ask whose details cannot be resolved:
   *  a non-preflight ask, a batched hold (one ask, N members — no single
   *  set of values to show), an operation whose pack declares no editable
   *  args. Rendered ONLY on the `open` page: once answered the hold is
   *  consumed and there is nothing left to resolve. */
  details?: readonly AskLandingDetail[];
  /** Optional heading for the details block — the held op's human summary
   *  ("Create a booking"). Absent ⇒ a neutral default. */
  details_heading?: string;
  /** D-210 A.8 3d-2c — why the previous submission was refused, re-rendered
   *  above the form so the owner can fix it in place.
   *
   *  A rejected edit that answers only `bad_request` is unusable on a phone:
   *  the page IS the surface, so a refusal it cannot explain is a refusal
   *  the owner cannot act on. */
  details_error?: string;
  /** The user's anti-phishing verification phrase (the A.6
   *  `NotificationSettings` field). Rendered in a recognizable block so
   *  a static phishing clone — which cannot know it — visibly fails the
   *  soft-trust check. Absent → the user set no phrase; no phrase block
   *  is rendered. */
  verification_phrase?: string;
  /** The server-issued single-use CSRF form-nonce — emitted as a hidden
   *  field; the POST route validates it back (the D-149 reception
   *  form-nonce pattern). Used only for an `open` ask; harmlessly
   *  ignored for an already-answered one. */
  form_nonce: string;
  /** The same-origin URL the option `<form>` POSTs to — the server owns
   *  its own routing, so the route supplies this. Used only for an
   *  `open` ask. */
  action: string;
}

/** A decoded landing-page POST. The `reply` is ready for
 *  `block.submitAnswer`; `form_nonce` is surfaced separately for the
 *  server route to validate against its single-use nonce store before
 *  it accepts the reply. */
export interface AskLandingSubmission {
  reply: InboundReply;
  form_nonce: string;
  /** D-210 A.8 3d-2c — raw `edit.<key>` values, prefix stripped, as
   *  SUBMITTED STRINGS. Undefined when the body carried none (the 3d-2b
   *  page, and every non-editable ask).
   *
   *  Deliberately un-coerced and un-validated here: the decoder knows the
   *  body's shape, not the operation's schema. `string` is what an
   *  `application/x-www-form-urlencoded` body actually contains, and
   *  pretending otherwise at this layer would mean guessing a type — and,
   *  for a datetime, a ZONE — that only the server can resolve. */
  edits?: Record<string, string>;
}

