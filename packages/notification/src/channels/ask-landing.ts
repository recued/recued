// ── Open page — the option form ────────────────────────────────────

/** One radio row per option. The `value` is the option `id` — the exact
 *  token the POST round-trips and `submitAnswer` re-validates against
 *  the persisted ask; the `label` is what the user reads. */
const renderOptionInputs = (options: readonly AskOption[]): string =>
  options
    .map(
      (option) => `<label class="option">
<input type="radio" name="option" value="${htmlEscape(option.id)}" required>
<span>${htmlEscape(option.label)}</span>
</label>`,
    )
    .join('\n');

const DEFAULT_DETAILS_HEADING = 'What this will do';

/** The "what will happen" block — the held operation's concrete values,
 *  label→value. Read-only in 3d-2b: these are exactly the args the page
 *  will let the owner EDIT in 3d-2c, so showing them first is the
 *  additive half. The empty list renders NOTHING rather than an empty
 *  frame — a block headed "What this will do" listing nothing is a worse
 *  claim than no block at all.
 *
 *  `<dl>` admits only `dt` / `dd` / `div` as children, so the legend sits
 *  outside it in the wrapping `<div class="details">`. */
const numAttr = (name: string, v: number | undefined): string =>
  v === undefined ? '' : ` ${name}="${htmlEscape(String(v))}"`;

/** One editable arg control. Submits under `edit.<key>`.
 *
 *  A `checkbox` carries NO `value` attribute on purpose: an unchecked box
 *  submits nothing at all, so presence-means-true / absence-means-false is
 *  the browser's own semantics, and the server reads it the same way the
 *  webclient inbox and the projection already do. */
const renderEditControl = (edit: AskLandingEditControl): string => {
  const name = htmlEscape(`${EDIT_KEY_PREFIX}${edit.key}`);
  const required = edit.required === true ? ' required' : '';
  if (edit.control === 'checkbox') {
    return `<input type="checkbox" name="${name}" value="on"${
      edit.checked === true ? ' checked' : ''
    }>`;
  }
  if (edit.control === 'textarea') {
    return `<textarea name="${name}"${required} rows="3">${htmlEscape(edit.value)}</textarea>`;
  }
  return `<input type="${htmlEscape(edit.control)}" name="${name}" value="${htmlEscape(
    edit.value,
  )}"${required}${numAttr('min', edit.min)}${numAttr('max', edit.max)}${
    edit.pattern !== undefined ? ` pattern="${htmlEscape(edit.pattern)}"` : ''
  }>`;
};

/** The refusal banner for a submission that came back rejected. */
const renderErrorBlock = (message: string | undefined): string =>
  message === undefined || message.length === 0
    ? ''
    : `\n<p class="error">${htmlEscape(message)}</p>`;

const renderDetailsBlock = (
  details: readonly AskLandingDetail[] | undefined,
  heading: string | undefined,
): string => {
  if (details === undefined || details.length === 0) return '';
  const rows = details
    .map((d) => {
      const cell =
        d.edit !== undefined
          ? renderEditControl(d.edit)
          : htmlEscape(d.value);
      return `<div class="detail${d.edit !== undefined ? ' detail--edit' : ''}">`
        + `<dt>${htmlEscape(d.label)}</dt><dd>${cell}</dd></div>`;
    })
    .join('\n');
  const legend =
    heading !== undefined && heading.length > 0 ? heading : DEFAULT_DETAILS_HEADING;
  return `\n<div class="details">
<span class="details-legend">${htmlEscape(legend)}</span>
<dl>
${rows}
</dl>
</div>`;
};

/** The `open`-ask body — the prompt, the message's optional context
 *  deep link, the held op's details, and a no-JS POST form. The hidden
 *  `form_nonce` (CSRF) + `ask_id` (so the decoder is self-contained,
 *  needing only the body, never the URL) ride as hidden fields. */
const renderOpenBody = (input: AskLandingRenderInput): string => {
  const { ask } = input;
  // The message's optional context deep link — rendered before the form
  // so the decision is made WITH the run / document it references in
  // view. Every other answer surface (`ui`, slack / telegram, the email
  // body) carries `link_url`, so the landing page does too;
  // `safeHttpUrl` gates the scheme before it becomes an `<a href>`.
  const safeLink =
    ask.message.link_url !== undefined
      ? safeHttpUrl(ask.message.link_url)
      : null;
  const linkLine =
    safeLink !== null
      ? `\n<p class="link"><a href="${htmlEscape(safeLink)}">${htmlEscape(safeLink)}</a></p>`
      : '';
  // ⚠ The details block sits INSIDE the form. Once a row can be an
  // `<input>` (3d-2c), a block rendered outside the form is a set of
  // controls the browser never submits — the owner would edit the slot,
  // approve, and the original value would be what lands. Read-only rows are
  // inert inside a form, so both shapes take the same position rather than
  // the position depending on a property of the rows.
  const detailsBlock = renderDetailsBlock(input.details, input.details_heading);
  return `<p class="prompt">${htmlEscape(ask.message.text)}</p>${linkLine}${renderErrorBlock(
    input.details_error,
  )}
<form method="POST" action="${htmlEscape(input.action)}">
<input type="hidden" name="form_nonce" value="${htmlEscape(input.form_nonce)}">
<input type="hidden" name="ask_id" value="${htmlEscape(ask.ask_id)}">${detailsBlock}
<fieldset>
<legend>Choose one</legend>
${renderOptionInputs(ask.options)}
</fieldset>
<button type="submit">Submit response</button>
</form>`;
};

// ── Answered page — honest cross-channel status ────────────────────

/** The label the user chose, resolved from the recorded answer's option
 *  id. Falls back to the raw id when the option is gone from the ask
 *  (mirrors D-149's `describeApprovalOutcome` fallback). */
const answeredOptionLabel = (ask: PendingAsk): string | null => {
  if (ask.answer === undefined) return null;
  const chosen = ask.options.find((o) => o.id === ask.answer?.option);
  return chosen !== undefined ? chosen.label : ask.answer.option;
};

/** The non-`open` body — the honest "already answered" page. Reached
 *  whatever channel the answer arrived on (the `PendingAsk` row is the
 *  shared cross-channel truth), so no hedge: it states the ask is done
 *  and, when an answer is recorded, echoes the chosen option. */
const renderAnsweredBody = (ask: PendingAsk): string => {
  const label = answeredOptionLabel(ask);
  const recorded =
    label !== null
      ? `\n<p class="recorded">Response recorded: ${htmlEscape(label)}</p>`
      : '';
  return `<p class="notice">This decision has already been answered — there is nothing for you to do here.</p>${recorded}`;
};

